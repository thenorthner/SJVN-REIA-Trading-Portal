// Modules that more than one vertical uses. Each is a function of the vertical
// it is being printed under, so the same module can be shown in every vertical
// that uses it with the wording that vertical needs.
//
// f(name, what, input, who, output, rules, status)
//   status is omitted for a functionality that is in the platform today, or
//   'pending: <why>' / 'partial: <what is missing>'.

export const f = (name, what, input, who, output, rules, st) => ({ name, what, input, who, output, rules, st });

const V = { reia: 'REIA', hydro: 'Hydro billing', trading: 'Power trading' };
const others = (all, me) => all.filter((k) => k !== me).map((k) => V[k]);

