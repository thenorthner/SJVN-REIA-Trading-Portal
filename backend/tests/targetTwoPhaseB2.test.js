import { describe, it, expect } from 'vitest';
import request from 'supertest';
import { app } from '../src/server.js';
import db from '../src/db/index.js';
import { tokenFor, auth, makeContract, makeEntity, makeInvoice } from './helpers/reia.js';

// Target #2, Phase B.2 (22-Oct-2026, docs/governance/TARGET-2-ROLE-TRANSFER.md):
// on the REIA desk the maker prepares, the checker decides, Finance concurs, and
// the REIA approver signs the last level and decides disputes. A checker does
// not create; a maker away is covered by an additional charge.

const post = (url, token, body = {}) => request(app).post(url).set(auth(token)).send(body);
const ack = { security_ack: 'test fixture: cover is tracked on the security desk' };

describe('a bill, from the maker to the approver', () => {
  it('is raised and submitted by the maker, and signed checker → Finance → approver', async () => {
    const contract = makeContract({ status: 'ACTIVE' });
    const maker = tokenFor('REIA_MAKER');
    const checker = tokenFor('REIA_CHECKER');
    const inv = makeInvoice({ contract_id: contract.id, status: 'DRAFT', total_amount: 36494000 });

    expect((await post(`/api/invoices/${inv.id}/submit-for-approval`, checker)).status, 'a checker submitted a bill').toBe(403);
    expect((await post(`/api/invoices/${inv.id}/submit-for-approval`, maker)).status).toBe(200);
    const levels = db.prepare('SELECT COUNT(*) c FROM invoice_approvals WHERE invoice_id = ?').get(inv.id).c;
    expect(levels).toBe(3);

    const act = (level, token) => post(`/api/invoices/${inv.id}/approvals/${level}/act`, token, { decision: 'APPROVED', comments: 'ok', ...ack });
    expect((await act(1, maker)).status, 'the maker signed level 1').toBe(403);
    expect((await act(1, checker)).status).toBe(200);
    expect((await act(2, tokenFor('FINANCE_USER'))).status).toBe(200);
    expect((await act(3, checker)).status, 'the checker signed the last level').toBe(403);
    expect((await act(3, tokenFor('REIA_APPROVER'))).status).toBe(200);
    expect(db.prepare('SELECT status FROM invoices WHERE id = ?').get(inv.id).status).toBe('APPROVED');
  });

  it('is generated by the maker only', async () => {
    const r = await post('/api/invoices/generate', tokenFor('REIA_CHECKER'), { contract_id: makeContract().id, period_month: '2026-09' });
    expect(r.status).toBe(403);
  });

  it('is withdrawn by the maker while a draft, and cancelled by the checker once with the reviewers', async () => {
    const contract = makeContract({ status: 'ACTIVE' });
    const draft = makeInvoice({ contract_id: contract.id, status: 'DRAFT' });
    expect((await post(`/api/invoices/${draft.id}/cancel`, tokenFor('REIA_CHECKER'), { reason: 'x' })).status).toBe(403);
    expect((await post(`/api/invoices/${draft.id}/cancel`, tokenFor('REIA_MAKER'), { reason: 'raised in error' })).status).toBe(200);
    const reviewing = makeInvoice({ contract_id: contract.id, status: 'UNDER_APPROVAL' });
    expect((await post(`/api/invoices/${reviewing.id}/cancel`, tokenFor('REIA_MAKER'), { reason: 'x' })).status).toBe(403);
    expect((await post(`/api/invoices/${reviewing.id}/cancel`, tokenFor('REIA_CHECKER'), { reason: 'duplicate of the June bill' })).status).toBe(200);
  });
});

describe('energy data', () => {
  it('is recorded by the maker and validated and locked by the checker', async () => {
    const contract = makeContract();
    const maker = tokenFor('REIA_MAKER');
    const checker = tokenFor('REIA_CHECKER');
    const body = { contract_id: contract.id, period_month: '2026-04', source: 'SELLER', energy_mwh: 15840 };
    expect((await post('/api/energy-data', checker, body)).status, 'a checker recorded energy').toBe(403);
    const row = (await post('/api/energy-data', maker, body)).body;
    expect((await post(`/api/energy-data/${row.id}/validate`, maker)).status, 'the maker validated their own figure').toBe(403);
    expect((await post(`/api/energy-data/${row.id}/validate`, checker)).body.status).toBe('VALIDATED');
    expect((await post(`/api/energy-data/${row.id}/lock`, maker)).status).toBe(403);
    expect((await post(`/api/energy-data/${row.id}/lock`, checker)).status).toBe(200);
  });
});

describe('a contract', () => {
  it('is drafted by the maker, and signed or ended by the checker', async () => {
    const c = makeContract({ status: 'DRAFT' });
    expect((await post(`/api/contracts/${c.id}/status`, tokenFor('REIA_CHECKER'), { status: 'UNDER_NEGOTIATION' })).status).toBe(403);
    expect((await post(`/api/contracts/${c.id}/status`, tokenFor('REIA_MAKER'), { status: 'UNDER_NEGOTIATION' })).status).toBe(200);
    expect((await post(`/api/contracts/${c.id}/status`, tokenFor('REIA_MAKER'), { status: 'TERMINATED', termination_reason: 'x' })).status).toBe(403);
  });
});

describe('a dispute (Target #2 H6)', () => {
  it('is run by the checker and decided by the REIA approver', async () => {
    const buyerCo = makeEntity('BUYER');
    const contract = makeContract({ buyer_id: buyerCo.id, contract_type: 'PSA' });
    const inv = makeInvoice({ contract_id: contract.id, direction: 'SJVN_TO_BUYER', status: 'SENT', total_amount: 400000, energy_charges: 400000 });
    const buyer = tokenFor('BUYER', { linked_entity_id: buyerCo.id });
    const d = (await post('/api/disputes', buyer, { invoice_id: inv.id, reason_code: 'TARIFF_RATE_ERROR', charge_line: 'energy_charges', disputed_amount: 50000, issue_description: 'rate applied is wrong' })).body;

    expect((await post(`/api/disputes/${d.id}/transition`, tokenFor('REIA_MAKER'), { status: 'UNDER_REVIEW' })).status, 'the maker moved a dispute on').toBe(403);
    expect((await post(`/api/disputes/${d.id}/transition`, tokenFor('REIA_CHECKER'), { status: 'UNDER_REVIEW' })).status).toBe(200);

    const decide = (token) => post(`/api/disputes/${d.id}/resolve`, token, { outcome: 'REJECTED', resolution_notes: 'The tariff schedule supports the rate billed' });
    expect((await decide(tokenFor('REIA_MAKER'))).status).toBe(403);
    expect((await decide(tokenFor('REIA_CHECKER'))).status, 'the checker decided a dispute').toBe(403);
    expect((await decide(tokenFor('REIA_APPROVER'))).status).toBe(200);
  });
});

