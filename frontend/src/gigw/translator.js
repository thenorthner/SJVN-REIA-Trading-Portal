const DICTS = {
  hi: TRANSLATIONS_HI,
  gu: TRANSLATIONS_GU,
  mr: TRANSLATIONS_MR
};

// Sorted phrase keys in descending length order for compound matching
const SORTED_KEYS = {
  hi: Object.keys(TRANSLATIONS_HI).sort((a, b) => b.length - a.length),
  gu: Object.keys(TRANSLATIONS_GU).sort((a, b) => b.length - a.length),
  mr: Object.keys(TRANSLATIONS_MR).sort((a, b) => b.length - a.length)
};

/**
 * Translates a single string for direct React code usage.
 */
export function tUI(text, lang = 'en') {
  if (!text || typeof text !== 'string' || lang === 'en') return text;
  const dict = DICTS[lang] || DICTS.hi;
  const trimmed = text.trim();
  if (dict[trimmed]) {
    return text.replace(trimmed, dict[trimmed]);
  }
  return translateString(text, lang);
}

function escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Replaces matching dictionary terms inside a string.
 */
export function translateString(text, lang = 'hi') {
  if (!text || typeof text !== 'string' || lang === 'en') return text;
  const dict = DICTS[lang] || DICTS.hi;
  const keys = SORTED_KEYS[lang] || SORTED_KEYS.hi;

  const trimmed = text.trim();
  if (dict[trimmed]) {
    return text.replace(trimmed, dict[trimmed]);
  }

  let result = text;
  for (let i = 0; i < keys.length; i++) {
    const key = keys[i];
    if (result.includes(key)) {
      // If key is a single alphanumeric word (e.g. "No", "All", "In"),
      // ONLY replace if it matches whole word boundary to avoid "No" -> "नहींthing"
      const isSingleWord = /^[A-Za-z0-9_]+$/.test(key);
      if (isSingleWord) {
        if (key === 'No') continue;
        const regex = new RegExp(`\\b${escapeRegExp(key)}\\b`, 'g');
        result = result.replace(regex, dict[key]);
      } else {
        result = result.split(key).join(dict[key]);
      }
    }
  }
  return result;
}

/**
 * Singleton DOM Translator that intercepts text nodes in #root and updates their content.
 */
class DomTranslator {
  constructor() {
    this.observer = null;
    this.currentLang = 'en';
    this.isTranslating = false;
    this.debounceTimer = null;
  }

  init() {
    if (typeof window === 'undefined' || typeof document === 'undefined') return;

    // Observe document body for changes
    if (!this.observer) {
      this.observer = new MutationObserver((mutations) => {
        if (this.currentLang === 'en' || this.isTranslating) return;

        let shouldSweep = false;
        for (const m of mutations) {
          if (m.type === 'childList' && m.addedNodes.length > 0) {
            shouldSweep = true;
            break;
          } else if (m.type === 'characterData') {
            // Our own writes leave nodeValue equal to __transText; anything else
            // is React putting new text in the node, which needs translating.
            const target = m.target;
            if (target && target.nodeValue && target.nodeValue !== target.__transText) {
              shouldSweep = true;
              break;
            }
          }
        }

        if (shouldSweep) {
          clearTimeout(this.debounceTimer);
          this.debounceTimer = setTimeout(() => {
            this.sweep(document.getElementById('root') || document.body, this.currentLang);
          }, 40);
        }
      });

      this.observer.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true
      });
    }
  }

  setLang(lang) {
    this.currentLang = lang;
    const root = document.getElementById('root') || document.body;
    if (!root) return;

    if (lang === 'en') {
      this.restore(root);
    } else {
      this.sweep(root, lang);
    }
  }

  translateNode(textNode, lang) {
    if (!textNode || textNode.nodeType !== Node.TEXT_NODE) return;
    const parent = textNode.parentElement;
    if (!parent) return;

    const tag = parent.tagName.toLowerCase();
    if (tag === 'script' || tag === 'style' || tag === 'code' || tag === 'pre' || tag === 'input' || tag === 'textarea' || tag === 'kbd') {
      return;
    }
    if (parent.closest('.notranslate') || parent.closest('[data-no-translate="true"]')) {
      return;
    }

    const val = textNode.nodeValue;
    if (!val || !val.trim()) return;

    // If the node no longer holds what we last wrote, React has re-rendered it
    // (for example a t() string in the newly chosen language), so its current
    // text is the new original. Keeping the old original would write the
    // previous language back over React's update until a reload.
    if (textNode.__origText === undefined || val !== textNode.__transText) {
      textNode.__origText = val;
    }

    const translated = translateString(textNode.__origText, lang);
    textNode.__transText = translated;
    if (translated !== val) {
      this.isTranslating = true;
      textNode.nodeValue = translated;
      this.isTranslating = false;
    }
  }

  restoreNode(textNode) {
    if (!textNode || textNode.nodeType !== Node.TEXT_NODE) return;
    if (textNode.__origText !== undefined) {
      // A node React has since rewritten already holds its English text.
      if (textNode.nodeValue === textNode.__transText) {
        this.isTranslating = true;
        textNode.nodeValue = textNode.__origText;
        this.isTranslating = false;
      }
      delete textNode.__origText;
      delete textNode.__transText;
    }
  }

  sweep(container, lang) {
    if (!container) return;
    this.init();

    const walker = document.createTreeWalker(container, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (tag === 'script' || tag === 'style' || tag === 'code' || tag === 'pre' || tag === 'input' || tag === 'textarea' || tag === 'kbd') {
          return NodeFilter.FILTER_REJECT;
        }
        if (parent.closest('.notranslate') || parent.closest('[data-no-translate="true"]')) {
          return NodeFilter.FILTER_REJECT;
        }
        if (!node.nodeValue || !node.nodeValue.trim()) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });

    const nodes = [];
    let n;
    while ((n = walker.nextNode())) {
      nodes.push(n);
    }

    for (let i = 0; i < nodes.length; i++) {
      this.translateNode(nodes[i], lang);
    }
  }

  restore(container) {
    if (!container) return;
    const walker = document.createTreeWalker(container, NodeFilter.SHOW_TEXT);
    const nodes = [];
    let n;
    while ((n = walker.nextNode())) {
      if (n.__origText !== undefined) nodes.push(n);
    }
    for (let i = 0; i < nodes.length; i++) {
      this.restoreNode(nodes[i]);
    }
  }
}

export const domTranslator = new DomTranslator();
